/* Send the screenshot to the Render backend */
analyzeButton.addEventListener("click", async function() {
  const baseUrl = backendInput.value.trim().replace(/\/+$/, "");
  const file = imageInput.files && imageInput.files[0];
  const question = document.getElementById("aiQuestion").value.trim();

  if (!baseUrl) {
    aiStatus.textContent = "Enter your Render backend URL first.";
    backendInput.focus();
    return;
  }

  if (!/^https:\/\/[^/]+/i.test(baseUrl)) {
    aiStatus.textContent = "Your backend URL must begin with https://";
    return;
  }

  if (!file) {
    aiStatus.textContent = "Choose a chart screenshot first.";
    imageInput.focus();
    return;
  }

  if (!question) {
    aiStatus.textContent = "Enter analysis instructions first.";
    return;
  }

  analyzeButton.disabled = true;
  analyzeButton.textContent = "Analyzing...";
  aiStatus.textContent = "Connecting to backend. Please wait.";
  aiResult.replaceChildren();
  const loading = document.createElement("div");
  loading.className = "ai-output";
  loading.textContent = "Sending your screenshot for analysis...";
  aiResult.appendChild(loading);

  try {
    const imageData = await new Promise(function(resolve, reject) {
      const reader = new FileReader();
      reader.onload = function() { resolve(reader.result); };
      reader.onerror = function() { reject(new Error("Unable to read the image.")); };
      reader.readAsDataURL(file);
    });

    const controller = new AbortController();
    const timeoutId = setTimeout(function() { controller.abort(); }, 120000);

    let response;
    try {
      response = await fetch(baseUrl + "/analyze-image", {
        method: "POST",
        headers: {"Content-Type": "application/json"},
        body: JSON.stringify({
          image: imageData,
          question: question
        }),
        signal: controller.signal
      });
    } finally {
      clearTimeout(timeoutId);
    }

    const data = await response.json().catch(function() { return {}; });

    if (!response.ok) {
      throw new Error(data.error || "Backend error: HTTP " + response.status);
    }

    const resultText = data.analysis || data.output || data.result;

    if (!resultText) {
      throw new Error("The backend returned no analysis text.");
    }

    const output = document.createElement("div");
    output.className = "ai-output";
    output.textContent = resultText;
    aiResult.replaceChildren(output);
    aiStatus.textContent = "Analysis received. Verify the observations on your chart.";
  } catch (error) {
    let message = error.message || "Unknown error";

    if (error.name === "AbortError") {
      message = "The request timed out. The free backend may be starting up; try again.";
    } else if (error instanceof TypeError) {
      message = "Could not connect. Check your Render URL, deployment status and backend CORS settings.";
    }

    const output = document.createElement("div");
    output.className = "ai-output red";
    output.textContent =
      "Analysis failed: " + message +
      "\n\nCheck that Render is running and the AI API key is configured in the server's Environment settings.";
    aiResult.replaceChildren(output);
    aiStatus.textContent = "Analysis could not be completed.";
  } finally {
    analyzeButton.disabled = false;
    analyzeButton.textContent = "Analyze Chart with AI";
  }
});

